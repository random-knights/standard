#!/usr/bin/env node
// Generates the per-tool install table in the plugin README and the MCP README
// from data/install-providers.json, the one place that says which tools the
// aieds receipt supports and how far each is verified.
//
// WHY. The same facts used to be typed by hand in the plugin README, the MCP
// README and the randomly.engineering install block, and they drifted. Now they
// are data. A tool marked "verified" must name a testedVersion and a fixture
// that exists in the repository; this script refuses anything else, so the
// claim cannot outrun the evidence (the plugin README's own bar).
//
// Usage:
//   node scripts/gen-install-table.mjs           rewrite the tables
//   node scripts/gen-install-table.mjs --check   fail if a README differs or the data breaks a rule
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
export const DATA_FILE = join(repoRoot, "data", "install-providers.json");
export const TARGETS = [
  join(repoRoot, "plugins", "random-knights", "README.md"),
  join(repoRoot, "mcp", "README.md"),
];
export const BEGIN = "<!-- install-providers:begin (generated by scripts/gen-install-table.mjs from data/install-providers.json; do not edit by hand) -->";
export const END = "<!-- install-providers:end -->";

const STATUS_WORD = {
  verified: "Verified",
  "numbers-verified": "Numbers verified, live hook not yet run",
  "on-demand": "On demand",
};
const FIXTURE_WORD = { "real-numbers": "real numbers", "shape-only": "shape only" };

export function loadData(file = DATA_FILE) {
  return JSON.parse(readFileSync(file, "utf8"));
}

/** Rule violations in the data, as readable strings. Empty means the data is allowed. */
export function problems(data, root = repoRoot) {
  const out = [];
  if (data?.schema !== "install-providers/1") out.push("schema must be install-providers/1");
  const ids = new Set();
  for (const p of data?.providers ?? []) {
    const where = `provider ${p?.id ?? "(no id)"}`;
    if (typeof p.id !== "string" || !/^[a-z0-9-]+$/.test(p.id)) out.push(`${where}: id must be a slug`);
    if (ids.has(p.id)) out.push(`${where}: duplicate id`);
    ids.add(p.id);
    if (typeof p.label !== "string" || p.label.length === 0) out.push(`${where}: label is required`);
    if (!Object.hasOwn(STATUS_WORD, p.status)) out.push(`${where}: status must be one of ${Object.keys(STATUS_WORD).join(", ")}`);
    if (!Array.isArray(p.install) || p.install.length === 0) out.push(`${where}: install lines are required`);
    // The evidence rule: every status above "unknown" names a version and a fixture that exists.
    if (typeof p.testedVersion !== "string" || p.testedVersion.length === 0) {
      out.push(`${where}: ${p.status} needs a testedVersion`);
    }
    if (typeof p.fixture !== "string" || p.fixture.length === 0) {
      out.push(`${where}: ${p.status} needs a fixture`);
    } else if (!existsSync(join(root, p.fixture))) {
      out.push(`${where}: fixture ${p.fixture} does not exist`);
    }
    if (!Object.hasOwn(FIXTURE_WORD, p.fixtureKind)) out.push(`${where}: fixtureKind must be real-numbers or shape-only`);
    for (const text of [p.label, p.receipt, p.note, ...(p.install ?? [])]) {
      if (typeof text === "string" && !/^[\x09\x0a\x20-\x7e]*$/.test(text)) out.push(`${where}: text must be ASCII`);
      if (typeof text === "string" && /[–—]/.test(text)) out.push(`${where}: no dashes`);
    }
  }
  if (!Array.isArray(data?.providers) || data.providers.length === 0) out.push("no providers");
  return out;
}

const cell = (s) => String(s).replace(/\|/g, "\\|");

/** The markdown table (no markers). */
export function renderTable(data) {
  const rows = [
    "| Tool | Status | Tested version | Receipt | Fixture | Install |",
    "| ---- | ------ | -------------- | ------- | ------- | ------- |",
  ];
  for (const p of data.providers) {
    const install = p.install.map((l) => `\`${cell(l)}\``).join("<br>");
    rows.push(
      `| ${cell(p.label)} | ${STATUS_WORD[p.status]} | ${cell(p.testedVersion)} | ${cell(p.receipt)} | ` +
        `\`${cell(p.fixture.split("/").pop())}\` (${FIXTURE_WORD[p.fixtureKind]}) | ${install} |`,
    );
  }
  return rows.join("\n");
}

/** Notes under the table, one bullet per tool, plus the meaning of each status in use. */
export function renderNotes(data) {
  const used = [...new Set(data.providers.map((p) => p.status))];
  const lines = [];
  for (const s of used) lines.push(`- **${STATUS_WORD[s]}**: ${data.statuses[s]}`);
  lines.push("");
  for (const p of data.providers) lines.push(`- **${p.label}**: ${p.note}`);
  return lines.join("\n");
}

export function renderBlock(data) {
  return `${BEGIN}\n\n${renderTable(data)}\n\n${renderNotes(data)}\n\n${END}`;
}

/** Returns the text with the generated block replaced; throws if the markers are missing. */
export function splice(text, block) {
  const a = text.indexOf(BEGIN);
  const b = text.indexOf(END);
  if (a < 0 || b < a) throw new Error("the install-providers markers are missing");
  return text.slice(0, a) + block + text.slice(b + END.length);
}

function main() {
  const check = process.argv.includes("--check");
  const data = loadData();
  const bad = problems(data);
  if (bad.length > 0) {
    for (const b of bad) console.error(`FAIL ${b}`);
    process.exit(1);
  }
  const block = renderBlock(data);
  let drift = false;
  for (const file of TARGETS) {
    const old = readFileSync(file, "utf8").replace(/\r\n/g, "\n");
    const next = splice(old, block);
    if (next === old) continue;
    if (check) {
      console.error(`FAIL ${file} differs from data/install-providers.json. Run: node scripts/gen-install-table.mjs`);
      drift = true;
    } else {
      writeFileSync(file, next);
      console.log(`wrote ${file}`);
    }
  }
  if (drift) process.exit(1);
  if (check) console.log("install tables match data/install-providers.json");
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
