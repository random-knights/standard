// Derives spec/v2/standard-versions.json from the three canonical documents.
//
// WHY THIS EXISTS. On 2026-09-15 the published site announced K13 at version
// 1.1.0 while K13.md, CITATION.k13.cff, the README template, the org profile
// page and three repo READMEs all said 2.0.0. The site had a literal typed into
// scripts/build-site.mjs; the documents had the truth; nothing compared them.
// Six hand-maintained copies of one fact is the drift condition this workspace
// keeps paying for, and the version column is the copy nobody rereads.
//
// So there is now ONE machine-readable statement of what each standard's
// current version is, derived from the document that defines it, served at
// https://standard.rand0m.ai/versions.json, and gated by
// spec/test/standard-versions.test.mjs so the committed file cannot disagree
// with the documents it is derived from.
//
// DELIBERATELY ABSENT: a generated-at timestamp. The committed file has to be
// byte-reproducible or the gate cannot compare it, and a clock reading would
// make every run differ. If you want to know when it changed, git knows.
//
// ALSO DELIBERATELY ABSENT: the emoji the README tables show. This file is
// walked by spec/test/ascii.test.mjs, whose exception list is deliberately
// nearly empty, and an emoji here would either break that gate or force a
// numeric-entity encoding into a data file. Presentation lives in the consumer
// that renders the table; this file carries only facts that can change.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
export const OUTPUT_PATH = join(repoRoot, "spec", "v2", "standard-versions.json");

/** Reads "**Version:** 1.2.3" out of a document, and refuses to guess. */
function readVersion(relPath) {
  const text = readFileSync(join(repoRoot, relPath), "utf8");
  const m = text.match(/\*\*Version:\*\*\s*([\d]+\.[\d]+\.[\d]+)/);
  if (!m) throw new Error(`Could not read a version out of ${relPath}.`);
  return m[1];
}

/** Reads "**Status:** ..." out of a document. */
function readStatus(relPath) {
  const text = readFileSync(join(repoRoot, relPath), "utf8");
  const m = text.match(/\*\*Status:\*\*\s*([^\n]+)/);
  return m ? m[1].trim() : "";
}

/**
 * The display string a README table shows. A draft is marked as one, because
 * a reader comparing "v1.0.0" against "v2.2.0" would otherwise take an
 * unratified draft for a shipped standard.
 */
function displayVersion(version, status) {
  return /draft/i.test(status) ? `v${version}-draft` : `v${version}`;
}

export function buildVersions() {
  const aiedsVersion = readVersion("spec/methodology.md");
  const factors = JSON.parse(
    readFileSync(join(repoRoot, "spec", "v2", "aieds-factors.json"), "utf8"),
  );
  if (factors.methodologyVersion !== aiedsVersion) {
    throw new Error(
      `spec/methodology.md declares ${aiedsVersion} but ` +
        `spec/v2/aieds-factors.json declares ${factors.methodologyVersion}.`,
    );
  }

  const eplusVersion = readVersion("eplus/v1/methodology.md");
  const eplusStatus = readStatus("eplus/v1/methodology.md");
  const k13Version = readVersion("K13.md");
  const k13Status = readStatus("K13.md");
  const aiedsStatus = readStatus("spec/methodology.md");

  return {
    $comment:
      "GENERATED by scripts/emit-standard-versions.mjs from the canonical " +
      "documents. Do not edit by hand: spec/test/standard-versions.test.mjs " +
      "re-derives this file and fails if the committed bytes differ. To move " +
      "a version, move it in the document that defines it and regenerate.",
    schemaVersion: 1,
    source: "https://standard.rand0m.ai/versions.json",
    standards: [
      {
        id: "eplus",
        name: "Earth+",
        version: displayVersion(eplusVersion, eplusStatus),
        semver: eplusVersion,
        status: eplusStatus,
        description: "Earth Health Scoring",
        canonicalText: "eplus/v1/methodology.md",
      },
      {
        id: "aieds",
        name: "AiEDs",
        version: displayVersion(aiedsVersion, aiedsStatus),
        semver: aiedsVersion,
        status: aiedsStatus,
        description: "AI Energy Disclosure",
        canonicalText: "spec/methodology.md",
      },
      {
        id: "k13",
        name: "K13",
        version: displayVersion(k13Version, k13Status),
        semver: k13Version,
        status: k13Status,
        description: "AI Response Summary",
        canonicalText: "K13.md",
      },
      {
        // Not a Random Knights standard and carries no version of ours. It is
        // in the table because the work follows the recommendations, so the
        // version cell is a middot rather than a number we would have to
        // invent. Kept here so the rendered table is fully generated and no
        // consumer hand-maintains a fourth row.
        id: "ai-for-good",
        name: "AI for Good",
        version: "&middot;",
        semver: null,
        status: "External recommendations, not a Random Knights standard",
        description: "(ITU) &middot; (UN) Recommendations",
        canonicalText: null,
      },
    ],
  };
}

export function serialise(versions) {
  return `${JSON.stringify(versions, null, 2)}\n`;
}

const invokedDirectly =
  process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (invokedDirectly) {
  writeFileSync(OUTPUT_PATH, serialise(buildVersions()), "utf8");
  process.stdout.write(`wrote ${OUTPUT_PATH}\n`);
}
